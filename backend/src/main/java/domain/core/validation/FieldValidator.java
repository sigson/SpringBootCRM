package domain.core.validation;

import java.lang.annotation.Annotation;
import java.util.Map;

/**
 * <h2>Базовый интерфейс валидатора реквизита.</h2>
 *
 * <p>Объявляет единственный переопределяемый метод {@link #validate}, который
 * вызывает механизм валидации. Конкретные виды проверки — это <b>интерфейсы-
 * валидаторы</b>, которые:
 * <ul>
 *   <li>фиксируют тип данных, которые потребляет проверка — аннотацию-ограничение
 *       {@code A} (её элементы {@code min}/{@code max}/{@code regex}/… и есть
 *       «описание потребляемых данных»);</li>
 *   <li>переопределяют {@link #validate} как {@code default}-метод интерфейса.</li>
 * </ul>
 *
 * <p>Чтобы добавить новый вид валидации, достаточно объявить такой интерфейс
 * (+ аннотацию, если её ещё нет). Ни механизм валидации, ни этот интерфейс при
 * этом не меняются — нет ни {@code switch}, ни перечня видов в сервисе.
 *
 * @param <A> аннотация-ограничение, параметры которой потребляет проверка
 */
public interface FieldValidator<A extends Annotation> {

    /**
     * Проверка значения. <b>Объявлен здесь, переопределяется {@code default}-
     * методом интерфейса-валидатора</b> и вызывается механизмом валидации.
     *
     * @param constraint экземпляр аннотации-ограничения (источник параметров)
     * @param value      нормализованное (trim) значение; {@code ""} для пустого
     * @return {@link ValidationResult#ok()} либо {@link ValidationResult#fail(String)}
     */
    ValidationResult validate(A constraint, String value);

    /**
     * Параметры ограничения для подсказок фронтенда (min/max/maxLength/pattern…).
     * По умолчанию пусто; интерфейс-валидатор переопределяет при необходимости.
     */
    default Map<String, Object> meta(A constraint) {
        return Map.of();
    }

    /**
     * Реагирует ли проверка на пустое значение. По умолчанию {@code false}
     * (пустое поле пропускается); переопределяет только проверка обязательности.
     */
    default boolean appliesToEmpty() {
        return false;
    }
}
