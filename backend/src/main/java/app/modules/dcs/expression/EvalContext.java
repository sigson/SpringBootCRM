package app.modules.dcs.expression;

import java.util.List;
import java.util.Map;

/**
 * Окружение, в котором вычисляется выражение компоновки.
 *
 * <p>Одно и то же выражение считается в трёх разных «точках»: на детальной записи,
 * на группировке и на общем итоге. Разницу между ними прячет именно контекст —
 * {@link #field(String)} отдаёт значение текущей строки (или значение группировки),
 * а {@link #rows()} — множество записей, по которому агрегируют {@code Сумма}/{@code Количество}.
 * Поэтому вычислитель не знает ничего про группировки и остаётся чистой функцией.
 */
public interface EvalContext {

    /** Значение поля в текущей точке вычисления; {@code null}, если поля нет. */
    Object field(String path);

    /** Значение параметра схемы (синтаксис {@code &Имя}). */
    Object parameter(String name);

    /** Записи текущей области — над ними работают агрегатные функции. */
    List<Map<String, Object>> rows();

    /** Уровень вложенности группировки (0 — общий итог). */
    int level();

    /** Порядковый номер записи в пределах области, начиная с 1. */
    int recordNumber();

    /**
     * {@code ВычислитьВыражение(выражение, группировка, областьВычисления)} — расчёт по
     * другой области: проценту от общего итога, нарастающему итогу, значению родителя.
     * Поддерживаемые области — {@code ОбщийИтог}/{@code GrandTotal},
     * {@code Иерархия}/{@code Hierarchy} (родительская группировка) и
     * {@code Группировка}/{@code Grouping} (текущая).
     */
    Object evaluateInScope(String expression, String grouping, String area);
}
