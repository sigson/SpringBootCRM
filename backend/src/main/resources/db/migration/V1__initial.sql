-- ============================================================================
-- 7. UNIVERSAL REFERENCE LOOKUP (skeleton)
-- ============================================================================
-- An empty skeleton view: the real content (UNION ALL over every catalog) is generated
-- by the application at startup (ReferenceLookupViewSynchronizer) from MetadataSnapshot.
-- The skeleton keeps reports/BI on reference_lookup from failing before the first run.
-- reference_lookup_version is a service table for idempotent regeneration
-- (a hash of the sorted (typeId, table) list).
-- ============================================================================
CREATE VIEW reference_lookup AS
    SELECT CAST(NULL AS BIGINT)  AS type_id,
           CAST(NULL AS VARCHAR) AS id,
           CAST(NULL AS VARCHAR) AS code,
           CAST(NULL AS VARCHAR) AS name,
           CAST(NULL AS VARCHAR) AS display
    WHERE 1 = 0;

CREATE TABLE reference_lookup_version (
    id            INT          PRIMARY KEY,
    content_hash  VARCHAR(64)  NOT NULL,
    updated_at    TIMESTAMP
);


