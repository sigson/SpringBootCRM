-- ----------------------------------------------------------------------------
-- ACCESS_ROLES - catalog of permission presets (typeId=9100)
-- ----------------------------------------------------------------------------
-- access_template stores a serialized AccessMetricPayload (the same
-- AccessMetricJsonConverter as user.access).
-- User<->AccessRole is one-to-one through users.role_*,
-- so there is no separate user_assigned_roles m2m table.
-- ----------------------------------------------------------------------------
CREATE TABLE access_roles (
    id                  UUID          PRIMARY KEY,
    code                VARCHAR(50)   NOT NULL UNIQUE,
    name                VARCHAR(200)  NOT NULL,
    description         VARCHAR(500),
    access_template     VARCHAR(4000) NOT NULL,
    enabled             BOOLEAN       NOT NULL DEFAULT TRUE,
    -- ---- AbstractAggregate audit ----
    own_access          VARCHAR(4000),
    version             BIGINT        NOT NULL DEFAULT 0,
    created_at          TIMESTAMP,
    updated_at          TIMESTAMP,
    created_by_type_id  BIGINT,
    created_by_id       UUID,
    updated_by_type_id  BIGINT,
    updated_by_id       UUID
);
CREATE INDEX idx_access_roles_code ON access_roles (code);


-- ============================================================================
-- 3. CATALOG INFRASTRUCTURE (code generation)
