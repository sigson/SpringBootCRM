-- ============================================================================
-- 1. CORE
-- ============================================================================

-- ----------------------------------------------------------------------------
-- USERS - accounts (UserAggregate, typeId=9001)
-- ----------------------------------------------------------------------------
-- The code/name columns, role_type_id/role_id (one role per
-- user) and interface_layout_* (the assigned interface)
-- are included in their final shape from the start.
-- password_hash is BCrypt; HIDDEN at field level (read only by the auth flow).
-- ----------------------------------------------------------------------------
CREATE TABLE users (
    id                        UUID          PRIMARY KEY,
    -- Catalog attributes
    code                      VARCHAR(50)   NOT NULL UNIQUE,
    name                      VARCHAR(200)  NOT NULL,
    username                  VARCHAR(100)  NOT NULL UNIQUE,
    email                     VARCHAR(200)  NOT NULL,
    display_name              VARCHAR(200),
    password_hash             VARCHAR(200)  NOT NULL,
    enabled                   BOOLEAN       NOT NULL DEFAULT TRUE,
    -- Role: AggregateReference<AccessRole, UUID> (nullable). 9100 = AccessRole.TYPE_ID.
    role_type_id              BIGINT,
    role_id                   UUID,
    -- Assigned interface: AggregateReference<InterfaceLayout, UUID> (nullable).
    -- NULL means the user gets the default mode. 9300 = InterfaceLayout.TYPE_ID.
    interface_layout_type_id  BIGINT,
    interface_layout_id       UUID,
    -- Per-instance ACL (AbstractAggregate) + per-user grants (UserAggregate)
    own_access                VARCHAR(4000),
    user_access               VARCHAR(4000),
    -- ---- AbstractAggregate audit ----
    version                   BIGINT        NOT NULL DEFAULT 0,
    created_at                TIMESTAMP,
    updated_at                TIMESTAMP,
    created_by_type_id        BIGINT,
    created_by_id             UUID,
    updated_by_type_id        BIGINT,
    updated_by_id             UUID
);
CREATE INDEX idx_users_username ON users (username);
CREATE INDEX idx_users_code     ON users (code);
CREATE INDEX idx_users_role_id  ON users (role_id);

-- ----------------------------------------------------------------------------
-- EVENT_OUTBOX — transactional event publishing (domain.core.eventing.OutboxEntity)
-- ----------------------------------------------------------------------------
CREATE TABLE event_outbox (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agg_type_id     BIGINT       NOT NULL,
    agg_id_raw      VARCHAR(200) NOT NULL,
    event_type      VARCHAR(200) NOT NULL,
    stable_name     VARCHAR(100) NOT NULL,
    version         INT          NOT NULL,
    payload_json    TEXT         NOT NULL,
    created_at      TIMESTAMP    NOT NULL,
    published_at    TIMESTAMP
);
CREATE INDEX idx_outbox_published ON event_outbox (published_at);
CREATE INDEX idx_outbox_aggref    ON event_outbox (agg_type_id, agg_id_raw);


-- ============================================================================
-- 2. ACCESS / ROLES
