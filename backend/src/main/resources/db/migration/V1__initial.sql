-- ============================================================================
-- 5. ACTIVITIES (typeId=5001)
-- ============================================================================
-- Activity extends the lean AbstractAggregate root: no
-- versioning, auditing or per-instance ACL. It carries only its declared attributes.
-- The row-level filter @AccessFiltered(userClaim=SELF_IDS) on owner_id makes Hibernate
-- add `owner_id IN (:selfIds)` (you see only your own activities); an admin bypasses it.
-- subject_* is a polymorphic UNION reference {User|Customer|LeadSource} (nullable).
-- ============================================================================
CREATE TABLE activities (
    id                  UUID          PRIMARY KEY,
    title               VARCHAR(200)  NOT NULL,
    description         VARCHAR(2000),
    starts_at           TIMESTAMP     NOT NULL,
    ends_at             TIMESTAMP     NOT NULL,
    -- AggregateReference<User, UUID> owner (required)
    owner_type_id       BIGINT        NOT NULL,
    owner_id            UUID          NOT NULL,
    -- Polymorphic "related object" reference (nullable)
    subject_type_id     BIGINT,
    subject_id          UUID
);
CREATE INDEX idx_activities_owner     ON activities (owner_id);
CREATE INDEX idx_activities_starts_at ON activities (starts_at);
CREATE INDEX idx_activities_subject   ON activities (subject_type_id, subject_id);


